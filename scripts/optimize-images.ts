/**
 * Card illustration pipeline (1909 Pamela Colman Smith Rider–Waite–Smith deck, public domain).
 *
 *   npm run images              resize originals already in assets/cards/source/
 *   npm run images -- --download  first fetch missing originals from Wikimedia Commons
 *   npm run images -- --docs      print the source table used in docs/ASSETS.md
 *
 * For every card it writes a 300px-wide thumbnail and a 900px-wide full image as WebP to
 * assets/cards/{thumb,full}/<card-id>.webp and regenerates src/data/cardImages.ts so the app bundles
 * them for offline use. Cards without an image keep the typographic CardFace.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import sharp from 'sharp';

import { DECK } from '../src/data/deck';

const ROOT = join(__dirname, '..');
const SOURCE = join(ROOT, 'assets', 'cards', 'source');
const THUMB = join(ROOT, 'assets', 'cards', 'thumb');
const FULL = join(ROOT, 'assets', 'cards', 'full');
const MAP_FILE = join(ROOT, 'src', 'data', 'cardImages.ts');

const USER_AGENT = 'MingalarTarotAssetPipeline/1.0 (offline tarot app; build-time download of public-domain scans)';

export const commonsPage = (file: string) => `https://commons.wikimedia.org/wiki/File:${file}`;
const commonsDownload = (file: string) =>
  `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(file)}`;

async function download(file: string, dest: string): Promise<void> {
  const res = await fetch(commonsDownload(file), { headers: { 'User-Agent': USER_AGENT }, redirect: 'follow' });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText}`);
  writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
}

function printDocs(): void {
  console.log('| Card id | Wikimedia Commons file |');
  console.log('| --- | --- |');
  for (const d of DECK) console.log(`| \`${d.id}\` | [${d.commonsFile}](${commonsPage(d.commonsFile)}) |`);
}

function writeMap(ids: string[]): void {
  const entries = (dir: string) =>
    ids.map((id) => `  '${id}': require('../../assets/cards/${dir}/${id}.webp'),`).join('\n');
  const body = (dir: string) => (ids.length ? `{\n${entries(dir)}\n}` : '{}');
  writeFileSync(
    MAP_FILE,
    `// Generated by \`npm run images\` (scripts/optimize-images.ts) from the 1909 Pamela Colman Smith
// scans listed in docs/ASSETS.md. Cards without an entry render the typographic CardFace instead.
import type { ImageSourcePropType } from 'react-native';

export const CARD_THUMBS: Readonly<Record<string, ImageSourcePropType>> = ${body('thumb')};

export const CARD_IMAGES: Readonly<Record<string, ImageSourcePropType>> = ${body('full')};
`,
  );
}

async function main(): Promise<void> {
  const args = new Set(process.argv.slice(2));
  if (args.has('--docs')) return printDocs();

  for (const dir of [SOURCE, THUMB, FULL]) mkdirSync(dir, { recursive: true });
  const done: string[] = [];
  const missing: string[] = [];

  for (const card of DECK) {
    const src = join(SOURCE, card.commonsFile);
    if (!existsSync(src) && args.has('--download')) {
      try {
        await download(card.commonsFile, src);
        console.log(`downloaded ${card.commonsFile}`);
      } catch (e) {
        console.error(`  ✗ ${card.commonsFile}: ${(e as Error).message}`);
      }
    }
    if (!existsSync(src)) {
      missing.push(card.id);
      continue;
    }
    const image = sharp(src).rotate();
    await image.clone().resize({ width: 300 }).webp({ quality: 80 }).toFile(join(THUMB, `${card.id}.webp`));
    await image.clone().resize({ width: 900 }).webp({ quality: 82 }).toFile(join(FULL, `${card.id}.webp`));
    done.push(card.id);
  }

  writeMap(done);
  console.log(`${done.length}/${DECK.length} cards processed; src/data/cardImages.ts updated.`);
  if (missing.length) {
    console.log(`${missing.length} cards have no source image yet (they use the typographic face).`);
    if (!args.has('--download')) console.log('Run `npm run images -- --download` to fetch them from Wikimedia Commons.');
  }
}

main().catch((e: unknown) => {
  console.error(e);
  process.exit(1);
});
